package main

// emit.go — Elixir guard-module emission.

import (
	"fmt"
	"sort"
	"strings"
)

type genOptions struct {
	SpecPath      string
	Namespace     string
	RuntimeModule string // module implementing :runtime-via checkers
	Strict        bool   // unsupported premises are errors instead of fail-closed checks
	AllDefines    bool   // emit every lowerable define, not only those premises call
}

type genResult struct {
	Code     string
	Warnings []string
	Guards   []string // struct modules, in emission order
}

func header(specPath, what string) string {
	return fmt.Sprintf("# Code generated by shengen-ex from %s. DO NOT EDIT.\n#\n%s\n", specPath, what)
}

// typespec renders the Elixir typespec for a Shen type.
func (st *SymbolTable) typespec(t string) string {
	switch t {
	case "string":
		return "String.t()"
	case "number":
		return "number()"
	case "boolean":
		return "boolean()"
	case "symbol":
		return "atom()"
	}
	if elem := listElemType(t); elem != "" {
		return "[" + st.typespec(elem) + "]"
	}
	if st.Lookup(t) != nil {
		return st.moduleFor(t) + ".t()"
	}
	return "term()"
}

// typeCheck renders a boolean Elixir expression asserting v inhabits t,
// or "" when the type is not something the emitter knows.
func (st *SymbolTable) typeCheck(t, v string) string {
	switch t {
	case "string":
		return "is_binary(" + v + ")"
	case "number":
		return "is_number(" + v + ")"
	case "boolean":
		return "is_boolean(" + v + ")"
	case "symbol":
		return "is_atom(" + v + ")"
	}
	if elem := listElemType(t); elem != "" {
		inner := st.typeCheck(elem, "e")
		if inner == "" {
			return "is_list(" + v + ")"
		}
		return "is_list(" + v + ") and Enum.all?(" + v + ", fn e -> " + inner + " end)"
	}
	info := st.Lookup(t)
	if info == nil {
		return ""
	}
	if info.Category == "sumtype" {
		return st.moduleFor(t) + ".member?(" + v + ")"
	}
	return "is_struct(" + v + ", " + st.moduleFor(t) + ")"
}

type field struct {
	shenVar  string
	name     string // struct key / accessor
	param    string // constructor parameter
	shenType string
}

// fieldsOf returns the struct layout of a concrete type.
func fieldsOf(info *TypeInfo) []field {
	premType := map[string]string{}
	for _, p := range info.Rule.Premises {
		premType[p.VarName] = p.TypeName
	}
	if len(info.Fields) > 0 {
		out := make([]field, len(info.Fields))
		for i, f := range info.Fields {
			t := f.ShenType
			if t == "unknown" {
				t = ""
			}
			out[i] = field{shenVar: f.ShenName, name: toSnake(f.ShenName), param: toSnake(f.ShenName), shenType: t}
		}
		return out
	}
	v := info.Rule.Conc.Fields[0]
	return []field{{shenVar: v, name: "val", param: toSnake(v), shenType: premType[v]}}
}

func indentLines(s, pad string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = pad + l
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// ruleText renders a rule back to readable Shen for @moduledoc.
func ruleText(info *TypeInfo) string {
	var b strings.Builder
	r := info.Rule
	for _, p := range r.Premises {
		fmt.Fprintf(&b, "%s : %s;\n", p.VarName, p.TypeName)
	}
	for _, v := range r.Verified {
		fmt.Fprintf(&b, "%s : verified;", v.Raw)
		if v.RuntimeVia != "" {
			fmt.Fprintf(&b, " \\* :runtime-via %s *\\", v.RuntimeVia)
		}
		b.WriteString("\n")
	}
	lhs := r.Conc.Items[0]
	if !r.Conc.IsWrapped {
		lhs = "[" + strings.Join(r.Conc.Items, " ") + "]"
	}
	fmt.Fprintf(&b, "==========\n%s : %s;\n", lhs, r.Conc.TypeName)
	return b.String()
}

func heredoc(s string) string {
	// Heredoc-safe: escape interpolation and backslashes.
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `#{`, `\#{`)
	s = strings.ReplaceAll(s, `"""`, `\"\"\"`)
	return s
}

func generateElixir(types []Datatype, defines []Define, st *SymbolTable, opt genOptions) (*genResult, error) {
	res := &genResult{}
	ns := opt.Namespace
	var body strings.Builder
	usedDefines := map[string]bool{}

	for _, name := range st.Order {
		info := st.Types[name]
		if info.Category == "sumtype" {
			continue
		}
		res.Guards = append(res.Guards, st.moduleFor(name))
	}

	// ---- concrete guard modules --------------------------------------
	for _, name := range st.Order {
		info := st.Types[name]
		if info.Category == "sumtype" {
			continue
		}
		mod := st.moduleFor(name)
		fs := fieldsOf(info)
		fmt.Fprintf(&body, "defmodule %s do\n", mod)
		label := fmt.Sprintf("Shen `%s` (%s", info.ShenName, info.Category)
		if info.Block != info.ShenName {
			label += fmt.Sprintf(", datatype `%s`", info.Block)
		}
		label += ")"
		if info.Rule.Conc.TypeName != info.ShenName {
			label += fmt.Sprintf(", a variant of `%s`", info.Rule.Conc.TypeName)
		}
		fmt.Fprintf(&body, "  @moduledoc \"\"\"\n  Guard type for %s.\n\n", heredoc(label))
		body.WriteString(indentLines(heredoc(ruleText(info)), "      "))
		body.WriteString("\n  Only `new/")
		fmt.Fprintf(&body, "%d` can build this struct; it checks every premise above.\n  \"\"\"\n\n", len(fs))

		keys := make([]string, len(fs))
		typed := make([]string, len(fs))
		params := make([]string, len(fs))
		paramSpecs := make([]string, len(fs))
		for i, f := range fs {
			keys[i] = ":" + f.name
			typed[i] = f.name + ": " + st.typespec(f.shenType)
			params[i] = f.param
			paramSpecs[i] = st.typespec(f.shenType)
		}
		fmt.Fprintf(&body, "  @enforce_keys [%s]\n", strings.Join(keys, ", "))
		fmt.Fprintf(&body, "  defstruct [%s]\n\n", strings.Join(keys, ", "))
		fmt.Fprintf(&body, "  @opaque t :: %%__MODULE__{%s}\n\n", strings.Join(typed, ", "))

		// constructor
		env := map[string]rexpr{}
		for _, f := range fs {
			env[f.shenVar] = rexpr{code: f.param, shenType: f.shenType}
		}
		pg := &premiseGen{st: st, env: env}
		var branches []string
		for _, f := range fs {
			chk := st.typeCheck(f.shenType, f.param)
			if chk == "" {
				continue
			}
			branches = append(branches, fmt.Sprintf("not (%s) ->\n        {:error, {:type, %s, [%s: %s]}}",
				chk, elixirLiteralString(f.shenVar+" : "+f.shenType), f.param, f.param))
		}
		for _, v := range info.Rule.Verified {
			code, vars, calls, err := pg.lowerPremise(v.Raw)
			kw := make([]string, len(vars))
			for i, vv := range vars {
				kw[i] = fmt.Sprintf("%s: %s", env[vv].code, env[vv].code)
			}
			if err != nil {
				msg := fmt.Sprintf("%s: premise %q cannot be lowered (%v)", info.ShenName, v.Raw, err)
				if opt.Strict {
					return nil, fmt.Errorf("%s", msg)
				}
				res.Warnings = append(res.Warnings, msg+"; emitted a fail-closed check")
				branches = append(branches, fmt.Sprintf("%s.Term.fail_closed() ->\n        {:error, {:unsupported_premise, %s, []}}",
					ns, elixirLiteralString(v.Raw)))
				continue
			}
			if v.RuntimeVia != "" {
				rtMod := opt.RuntimeModule
				if rtMod == "" {
					rtMod = ns + ".Runtime"
				}
				args := make([]string, len(vars))
				for i, vv := range vars {
					args[i] = env[vv].code
				}
				code = fmt.Sprintf("%s.%s(%s) == true", rtMod, fnName(v.RuntimeVia), strings.Join(args, ", "))
			} else {
				for _, c := range calls {
					usedDefines[c] = true
				}
			}
			branches = append(branches, fmt.Sprintf("%s ->\n        {:error, {:premise, %s, [%s]}}",
				negate(code), elixirLiteralString(v.Raw), strings.Join(kw, ", ")))
		}
		assigns := make([]string, len(fs))
		for i, f := range fs {
			assigns[i] = f.name + ": " + f.param
		}
		okExpr := fmt.Sprintf("{:ok, %%__MODULE__{%s}}", strings.Join(assigns, ", "))

		fmt.Fprintf(&body, "  @doc \"Builds a `%s` value, checking every premise of the Shen rule.\"\n", info.ShenName)
		fmt.Fprintf(&body, "  @spec new(%s) :: {:ok, t()} | {:error, %s.GuardError.reason()}\n", strings.Join(paramSpecs, ", "), ns)
		if len(branches) == 0 {
			fmt.Fprintf(&body, "  def new(%s), do: %s\n\n", strings.Join(params, ", "), okExpr)
		} else {
			fmt.Fprintf(&body, "  def new(%s) do\n    cond do\n", strings.Join(params, ", "))
			for _, br := range branches {
				fmt.Fprintf(&body, "      %s\n\n", br)
			}
			fmt.Fprintf(&body, "      true ->\n        %s\n    end\n  end\n\n", okExpr)
		}
		fmt.Fprintf(&body, "  @doc \"Like `new/%d` but raises `%s.GuardError` when a premise fails.\"\n", len(fs), ns)
		fmt.Fprintf(&body, "  @spec new!(%s) :: t()\n", strings.Join(paramSpecs, ", "))
		fmt.Fprintf(&body, "  def new!(%s) do\n    case new(%s) do\n      {:ok, guard} -> guard\n      {:error, reason} -> raise %s.GuardError, guard: __MODULE__, reason: reason\n    end\n  end\n\n",
			strings.Join(params, ", "), strings.Join(params, ", "), ns)

		for _, f := range fs {
			fmt.Fprintf(&body, "  @doc \"The `%s` field.\"\n", f.shenVar)
			fmt.Fprintf(&body, "  @spec %s(t()) :: %s\n", f.name, st.typespec(f.shenType))
			fmt.Fprintf(&body, "  def %s(%%__MODULE__{%s: value}), do: value\n\n", f.name, f.name)
		}

		// Shen representation
		var shen string
		fieldByVar := map[string]field{}
		for _, f := range fs {
			fieldByVar[f.shenVar] = f
		}
		render := func(f field) string {
			if isPrimitive(f.shenType) {
				return "guard." + f.name
			}
			if elem := listElemType(f.shenType); elem != "" && isPrimitive(elem) {
				return "guard." + f.name
			}
			return ns + ".Term.to_shen(guard." + f.name + ")"
		}
		if info.Rule.Conc.IsWrapped {
			shen = render(fs[0])
		} else {
			parts := make([]string, len(info.Rule.Conc.Items))
			for i, item := range info.Rule.Conc.Items {
				if f, ok := fieldByVar[item]; ok {
					parts[i] = render(f)
					continue
				}
				n, err := readShen(item)
				lit := ""
				ok := false
				if err == nil {
					lit, ok = literal(n)
				}
				if !ok {
					return nil, fmt.Errorf("%s: conclusion item %q is neither a premise variable nor a literal", info.ShenName, item)
				}
				parts[i] = lit
			}
			shen = "[" + strings.Join(parts, ", ") + "]"
		}
		fmt.Fprintf(&body, "  @doc false\n  def __shen__(%%__MODULE__{} = guard), do: %s\n\n", shen)
		fmt.Fprintf(&body, "  @doc false\n  def __shen_type__, do: %s\n", elixirLiteralString(info.Rule.Conc.TypeName))
		body.WriteString("end\n\n")
	}

	// ---- sum types -----------------------------------------------------
	for _, sum := range st.SumTypeNames() {
		variants := st.SumTypes[sum]
		mods := make([]string, len(variants))
		specs := make([]string, len(variants))
		for i, v := range variants {
			mods[i] = st.moduleFor(v)
			specs[i] = mods[i] + ".t()"
		}
		fmt.Fprintf(&body, "defmodule %s do\n", st.moduleFor(sum))
		fmt.Fprintf(&body, "  @moduledoc \"\"\"\n  Sum type `%s`: a value built by any of its variant rules.\n  \"\"\"\n\n", sum)
		fmt.Fprintf(&body, "  @type t :: %s\n\n", strings.Join(specs, " | "))
		fmt.Fprintf(&body, "  @variants [%s]\n\n", strings.Join(mods, ", "))
		body.WriteString("  @doc \"Variant modules of this sum type.\"\n  @spec variants() :: [module()]\n  def variants, do: @variants\n\n")
		body.WriteString("  @doc \"True when `value` was built by one of the variant constructors.\"\n  @spec member?(term()) :: boolean()\n")
		body.WriteString("  def member?(%{__struct__: module}) when module in @variants, do: true\n  def member?(_), do: false\nend\n\n")
	}

	// ---- defines used by premises -------------------------------------
	if opt.AllDefines {
		for _, d := range defines {
			usedDefines[d.Name] = true
		}
	}
	if len(usedDefines) > 0 {
		names := definesUsed(usedDefines, defines)
		dg := &defineGen{st: st, defs: map[string]*Define{}}
		for i := range defines {
			dg.defs[defines[i].Name] = &defines[i]
		}
		fmt.Fprintf(&body, "defmodule %s.Defines do\n", ns)
		body.WriteString("  @moduledoc \"\"\"\n  Elixir lowering of Shen `(define ...)` blocks (those verified premises call, or all with --all-defines).\n\n")
		body.WriteString("  Arguments are converted to their Shen representation first, so the\n  bodies run with Shen data semantics (first-match clauses, non-linear\n  patterns, `where` guards).\n  \"\"\"\n\n")
		for _, name := range names {
			d := dg.defs[name]
			impl, err := dg.lowerDefine(d)
			if err != nil {
				return nil, err
			}
			arity := len(d.Clauses[0].Patterns)
			args := make([]string, arity)
			conv := make([]string, arity)
			specs := make([]string, arity)
			for i := range args {
				args[i] = fmt.Sprintf("a%d", i+1)
				conv[i] = fmt.Sprintf("%s.Term.to_shen(a%d)", ns, i+1)
				specs[i] = "term()"
			}
			sig := ""
			if d.RetType != "" {
				sig = "{" + strings.Join(append(append([]string{}, d.ParamType...), d.RetType), " --> ") + "}"
			}
			fmt.Fprintf(&body, "  @doc \"Shen `%s` %s\"\n", name, heredocInline(sig))
			fmt.Fprintf(&body, "  @spec %s(%s) :: term()\n", fnName(name), strings.Join(specs, ", "))
			fmt.Fprintf(&body, "  def %s(%s), do: %s(%s)\n\n", fnName(name), strings.Join(args, ", "), implName(name), strings.Join(conv, ", "))
			body.WriteString(impl)
			body.WriteString("\n")
		}
		out := strings.TrimRight(body.String(), "\n")
		body.Reset()
		body.WriteString(out + "\nend\n\n")
	}

	// ---- assemble ------------------------------------------------------
	var b strings.Builder
	b.WriteString(header(opt.SpecPath, fmt.Sprintf(`# Guard types for the Shen spec. Every struct is @opaque and only its
# new/N constructor can build it; new/N checks each premise of the Shen
# sequent rule and returns {:error, {:premise, "<shen premise>", values}}
# on violation. Compile with %s.GuardTracer (generated
# separately) so %%Guard{} literals outside this file fail to compile.`, ns)))
	b.WriteString("\n")
	fmt.Fprintf(&b, "defmodule %s do\n", ns)
	fmt.Fprintf(&b, "  @moduledoc \"\"\"\n  Registry for the guard types generated from `%s`.\n  \"\"\"\n\n", heredoc(opt.SpecPath))
	fmt.Fprintf(&b, "  @guards [\n%s  ]\n\n", listLines(res.Guards, "    "))
	b.WriteString("  @doc \"Every generated guard struct module.\"\n  @spec guards() :: [module()]\n  def guards, do: @guards\n\n")
	fmt.Fprintf(&b, "  @doc \"The spec these guards were generated from.\"\n  @spec spec_path() :: String.t()\n  def spec_path, do: %s\nend\n\n", elixirLiteralString(opt.SpecPath))

	fmt.Fprintf(&b, "defmodule %s.GuardError do\n", ns)
	b.WriteString("  @moduledoc \"Raised by `new!/N` when a Shen premise does not hold.\"\n\n")
	b.WriteString("  @type reason ::\n          {:premise, String.t(), keyword()}\n          | {:type, String.t(), keyword()}\n          | {:unsupported_premise, String.t(), keyword()}\n\n")
	b.WriteString("  defexception [:guard, :reason]\n\n")
	b.WriteString("  @impl true\n  def message(%{guard: guard, reason: {kind, premise, values}}) do\n")
	b.WriteString("    \"#{inspect(guard)}: #{kind} #{premise} failed for #{inspect(values)}\"\n  end\nend\n\n")

	fmt.Fprintf(&b, "defmodule %s.Term do\n", ns)
	b.WriteString("  @moduledoc \"\"\"\n  Shen representation of guard values: wrappers become their primitive,\n  composites become lists in conclusion order.\n  \"\"\"\n\n")
	fmt.Fprintf(&b, "  @guards %s.guards()\n\n", ns)
	b.WriteString("  @doc \"Converts a (possibly nested) guard value to its Shen representation.\"\n  @spec to_shen(term()) :: term()\n")
	b.WriteString("  def to_shen(%{__struct__: module} = value) when module in @guards, do: module.__shen__(value)\n")
	b.WriteString("  def to_shen(list) when is_list(list), do: Enum.map(list, &to_shen/1)\n")
	b.WriteString("  def to_shen(value), do: value\n\n")
	b.WriteString("  @doc false\n  @spec fail_closed() :: true\n  def fail_closed, do: true\nend\n\n")

	b.WriteString(body.String())
	res.Code = strings.TrimRight(b.String(), "\n") + "\n"
	sort.Strings(res.Warnings)
	return res, nil
}

func heredocInline(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, `#{`, `\#{`)
	return s
}

func listLines(items []string, pad string) string {
	var b strings.Builder
	for i, it := range items {
		b.WriteString(pad + it)
		if i < len(items)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	return b.String()
}

