func generateTracer(res *genResult, opt genOptions, guardsFile, tracerFile string) string {
	ns := opt.Namespace
	var b strings.Builder
	b.WriteString(header(opt.SpecPath, fmt.Sprintf(`# Compile-time forgery tracer for the guard structs in
# %s.
#
# mix usage: the tracer must be loaded before the project compiles, so it
# lives outside elixirc_paths and is required from mix.exs:
#
#     # mix.exs
#     Code.require_file("%s", __DIR__)
#
#     def project do
#       [
#         ...,
#         elixirc_options: [tracers: [%s.GuardTracer]]
#       ]
#     end
#
# It raises a CompileError for
#   * %%Guard{...} struct literals and %%Guard{g | ...} struct updates outside
#     the guard's own module (pattern matching on %%Guard{} is allowed);
#   * Kernel.struct/2 or Kernel.struct!/2 in any module that also references
#     a guard type (the tracer cannot see struct/2 arguments, so it refuses
#     the combination; keep struct/2 and defexception in modules that do not
#     touch guard types). Modules under %s.* are generated and exempt.
# Not visible to compiler tracers: map-update syntax (%%{g | k: v}), raw
# __struct__ maps, and guard modules passed around as runtime values to a
# module that never names them. @opaque + Dialyzer and the tcb audit
# cover the first two; see docs/REFERENCE.md for the full list.`, guardsFile, tracerFile, ns, ns)))
	b.WriteString("\n")
	fmt.Fprintf(&b, "defmodule %s.GuardTracer do\n", ns)
	b.WriteString("  @moduledoc false\n\n")
	fmt.Fprintf(&b, "  @guards [\n%s  ]\n\n", listLines(res.Guards, "    "))
	fmt.Fprintf(&b, "  @generated_prefix %s\n\n", elixirLiteralString(ns+"."))
	b.WriteString(`  @doc false
  def guards, do: @guards

  @doc false
  def trace({:struct_expansion, meta, module, _keys}, env) when module in @guards do
    cond do
      env.module == module -> :ok
      Macro.Env.in_match?(env) -> :ok
      true ->
        refuse(env.file, meta, env, "#{inspect(module)} is a Shen guard type; build it with #{inspect(module)}.new/N instead of a struct literal")
    end
  end

  def trace({:alias_reference, _meta, module}, env) when module in @guards do
    unless generated?(env.module), do: remember(env.module, :guard_ref, true)
    :ok
  end

  def trace({kind, meta, Kernel, name, _arity}, env)
      when kind in [:remote_function, :imported_function] and name in [:struct, :struct!] do
    unless generated?(env.module), do: remember(env.module, :struct_call, {name, meta, env.file})
    :ok
  end

  def trace({:on_module, _bytecode, _}, env) do
    state = Process.delete({__MODULE__, env.module}) || %{}

    case state do
      %{guard_ref: true, struct_call: {name, meta, file}} ->
        refuse(file, meta, env, "Kernel.#{name}/2 is not allowed in #{inspect(env.module)}: the module references Shen guard types and struct/2 could forge one")

      _ ->
        :ok
    end
  end

  def trace(_event, _env), do: :ok

  defp generated?(nil), do: false
  defp generated?(module), do: String.starts_with?(inspect(module), @generated_prefix)

  defp remember(module, key, value) do
    state = Process.get({__MODULE__, module}, %{})
    Process.put({__MODULE__, module}, Map.put_new(state, key, value))
  end

  defp refuse(file, meta, env, description) do
    raise CompileError, file: file, line: Keyword.get(meta, :line, env.line), description: description
  end
end
`)
	return b.String()
}
